"""Rebuild data/marlowe-data.js from the CSV files in data/.

Coaches only: run this after changing any CSV, then commit both.
    python3 tools/build_data.py

Learners never need to run it. The page loads data/marlowe-data.js directly.
"""
import csv
import json
import pathlib

DATA_DIR = pathlib.Path(__file__).resolve().parent.parent / "data"

# Same order as the side panel on the page.
TABLES = [
    "crime_scene_reports",
    "people",
    "witness_statements",
    "key_cards",
    "door_swipes",
    "cloakroom_log",
    "bar_tabs",
    "phone_calls",
]


def main():
    data = {}
    for table in TABLES:
        with open(DATA_DIR / f"{table}.csv", newline="", encoding="utf-8") as f:
            rows = list(csv.reader(f))
        data[table] = {"columns": rows[0], "rows": rows[1:]}

    out = DATA_DIR / "marlowe-data.js"
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_data.py from the CSV files in this folder. Do not edit by hand.\n")
        f.write("window.MARLOWE_DATA = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
